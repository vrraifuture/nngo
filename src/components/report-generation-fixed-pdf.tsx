  const downloadCSVReport = async (report: Report) => {
    try {
      console.log("Generating CSV report for:", report.name);

      const csvContent = [
        ["Report Name", "Type", "Generated Date", "Generated By"],
        [
          sanitizeInput(report.name),
          report.type.replace("_", " ").toUpperCase(),
          new Date(report.generated_at).toLocaleDateString(),
          sanitizeInput(report.generated_by),
        ],
        [],
        ["Report Data", "", "", ""],
      ];

      try {
        if (report.type === "financial_summary") {
          const { data: funds } = await supabase
            .from("fund_sources")
            .select("*");
          const { data: expenses } = await supabase
            .from("expenses")
            .select("*")
            .in("status", ["approved", "paid"]);

          const totalFunds =
            funds?.reduce((sum, f) => sum + (f.amount || 0), 0) || 0;
          const totalExpenses =
            expenses?.reduce((sum, e) => sum + (e.amount || 0), 0) || 0;

          csvContent.push(["Financial Overview", "Amount (FRw)", "Status"]);
          csvContent.push([
            "Total Funds",
            totalFunds.toLocaleString(),
            "Confirmed",
          ]);
          csvContent.push([
            "Total Expenses",
            totalExpenses.toLocaleString(),
            "Verified",
          ]);
          csvContent.push([
            "Balance",
            (totalFunds - totalExpenses).toLocaleString(),
            "Available",
          ]);

          if (funds?.length) {
            csvContent.push(
              [],
              ["Fund Sources", "Amount (FRw)", "Type", "Date"],
            );
            funds.forEach((fund) => {
              csvContent.push([
                fund.name,
                (fund.amount || 0).toLocaleString(),
                fund.is_restricted ? "Restricted" : "Unrestricted",
                fund.received_date || "N/A",
              ]);
            });
          }
        } else if (report.type === "expense_report") {
          const { data: expenses } = await supabase
            .from("expenses")
            .select("*, budget_categories(name)")
            .in("status", ["approved", "paid"]);

          if (expenses?.length) {
            csvContent.push([
              "Expense Item",
              "Amount (FRw)",
              "Category",
              "Date",
              "Status",
            ]);
            expenses.forEach((expense) => {
              csvContent.push([
                expense.title,
                (expense.amount || 0).toLocaleString(),
                expense.budget_categories?.name || "Uncategorized",
                expense.expense_date || "N/A",
                expense.status,
              ]);
            });
          }
        } else if (report.type === "budget_variance") {
          const { data: categories } = await supabase
            .from("budget_categories")
            .select("*, expenses(amount, status)");

          if (categories?.length) {
            csvContent.push([
              "Category",
              "Budget (FRw)",
              "Actual (FRw)",
              "Variance (FRw)",
              "Variance %",
              "Status",
            ]);
            categories.forEach((category) => {
              const budgetAmount = category.budget_amount || 0;
              const actualExpenses =
                category.expenses
                  ?.filter(
                    (e) => e.status === "approved" || e.status === "paid",
                  )
                  ?.reduce((sum, e) => sum + (e.amount || 0), 0) || 0;

              const variance = budgetAmount - actualExpenses;
              const variancePercent =
                budgetAmount > 0
                  ? ((variance / budgetAmount) * 100).toFixed(1)
                  : "0";

              csvContent.push([
                category.name,
                budgetAmount.toLocaleString(),
                actualExpenses.toLocaleString(),
                variance.toLocaleString(),
                `${variancePercent}%`,
                variance >= 0 ? "Under Budget" : "Over Budget",
              ]);
            });
          }
        } else if (report.type === "donor_report") {
          const { data: fundSources } = await supabase
            .from("fund_sources")
            .select("*, donors(name)");

          if (fundSources?.length) {
            csvContent.push(["Donor Name", "Amount (FRw)", "Fund", "Date"]);
            fundSources.forEach((fund) => {
              csvContent.push([
                fund.donors?.name || "Anonymous",
                (fund.amount || 0).toLocaleString(),
                fund.name,
                fund.received_date || "N/A",
              ]);
            });
          }
        }
      } catch (dataError) {
        csvContent.push([
          "Error",
          "Unable to fetch real data",
          dataError.message || "Unknown error",
        ]);
      }

      // Add footer
      csvContent.push(
        [],
        ["Report Footer", "", "", ""],
        ["Generated By", "Pryro for NGO System", "", ""],
        ["Export Time", new Date().toLocaleString(), "", ""],
        ["File Format", "CSV", "", ""],
      );

      // Convert to CSV string
      const csvString = csvContent
        .map((row) =>
          row
            .map((cell) => {
              const cellValue = (cell || "").toString();
              if (
                cellValue.includes(",") ||
                cellValue.includes('"') ||
                cellValue.includes("\n")
              ) {
                return `"${cellValue.replace(/"/g, '""')}"`;
              }
              return cellValue;
            })
            .join(","),
        )
        .join("\n");

      // Validate content
      if (!validateContent(csvString, 100)) {
        throw new Error("CSV content is insufficient");
      }

      // Create and download file
      const BOM = "\uFEFF"; // UTF-8 BOM for Excel compatibility
      const blob = new Blob([BOM + csvString], {
        type: "text/csv;charset=utf-8;",
      });

      if (blob.size === 0) {
        throw new Error("Failed to create CSV blob");
      }

      const url = window.URL.createObjectURL(blob);
      const a = document.createElement("a");
      a.href = url;
      a.download = `${sanitizeInput(report.name).replace(/[^a-zA-Z0-9]/g, "_")}.csv`;
      document.body.appendChild(a);
      a.click();
      document.body.removeChild(a);
      window.URL.revokeObjectURL(url);

      alert(`CSV report "${report.name}" downloaded successfully!`);
    } catch (error) {
      console.error("CSV generation error:", error);
      alert("Error generating CSV report. Please try again.");
    }
  };

