// Utility function to sanitize user input
const sanitizeInput = (input: string): string => {
  if (!input) return "";
  return input
    .replace(/[\r\n]/g, " ")
    .replace(/[<>'"&]/g, (char) => {
      const entities: { [key: string]: string } = {
        "<": "&lt;",
        ">": "&gt;",
        '"': "&quot;",
        "'": "&#x27;",
        "&": "&amp;",
      };
      return entities[char] || char;
    })
    .trim();
};

// Enhanced content validation
const validateContent = (content: string, minLength: number = 100): boolean => {
  return Boolean(content && content.trim().length >= minLength);
};

// Generate real data content for reports
const generateReportContent = async (
  report: Report,
  supabase: any,
): Promise<string> => {
  const reportData = {
    name: sanitizeInput(report.name),
    type: report.type.replace("_", " ").toUpperCase(),
    generatedAt: new Date(report.generated_at).toLocaleDateString(),
    generatedBy: sanitizeInput(report.generated_by),
    description: sanitizeInput(report.description || ""),
  };

  let content = `REPORT: ${reportData.name}\n\n`;
  content += `Type: ${reportData.type}\n`;
  content += `Generated: ${reportData.generatedAt}\n`;
  content += `Generated By: ${reportData.generatedBy}\n`;
  content += `Description: ${reportData.description}\n\n`;

  try {
    if (report.type === "financial_summary") {
      const { data: funds } = await supabase.from("fund_sources").select("*");
      const { data: expenses } = await supabase
        .from("expenses")
        .select("*")
        .in("status", ["approved", "paid"]);

      const totalFunds =
        funds?.reduce((sum, f) => sum + (f.amount || 0), 0) || 0;
      const totalExpenses =
        expenses?.reduce((sum, e) => sum + (e.amount || 0), 0) || 0;
      const balance = totalFunds - totalExpenses;
      const utilizationRate =
        totalFunds > 0 ? ((totalExpenses / totalFunds) * 100).toFixed(1) : "0";

      content += `FINANCIAL SUMMARY REPORT\n========================\n\n`;
      content += `Total Funds Received: FRw ${totalFunds.toLocaleString()}\n`;
      content += `Total Expenses: FRw ${totalExpenses.toLocaleString()}\n`;
      content += `Remaining Balance: FRw ${balance.toLocaleString()}\n`;
      content += `Fund Utilization Rate: ${utilizationRate}%\n\n`;

      if (funds?.length) {
        content += `FUND SOURCES:\n`;
        funds.forEach((fund) => {
          content += `- ${fund.name}: FRw ${(fund.amount || 0).toLocaleString()} (${fund.is_restricted ? "Restricted" : "Unrestricted"})\n`;
        });
        content += `\n`;
      }
    } else if (report.type === "expense_report") {
      const { data: expenses } = await supabase
        .from("expenses")
        .select("*, budget_categories(name), projects(name)")
        .in("status", ["approved", "paid"]);

      const totalExpenses =
        expenses?.reduce((sum, e) => sum + (e.amount || 0), 0) || 0;
      const avgExpense = expenses?.length ? totalExpenses / expenses.length : 0;

      content += `EXPENSE ANALYSIS REPORT\n=======================\n\n`;
      content += `Total Expenses: FRw ${totalExpenses.toLocaleString()}\n`;
      content += `Number of Transactions: ${expenses?.length || 0}\n`;
      content += `Average Expense: FRw ${Math.round(avgExpense).toLocaleString()}\n\n`;

      if (expenses?.length) {
        content += `DETAILED EXPENSES:\n`;
        expenses.slice(0, 20).forEach((expense, i) => {
          const category = expense.budget_categories?.name || "Uncategorized";
          const project = expense.projects?.name || "General";
          content += `${i + 1}. ${expense.title} - FRw ${(expense.amount || 0).toLocaleString()} (${category}) - ${expense.expense_date} - ${expense.status}\n`;
        });
        content += `\n`;
      }
    } else if (report.type === "budget_variance") {
      const { data: categories } = await supabase
        .from("budget_categories")
        .select("*, expenses(amount, status)");

      content += `BUDGET VARIANCE REPORT\n======================\n\n`;

      if (categories?.length) {
        let totalBudget = 0;
        let totalActual = 0;

        content += `CATEGORY ANALYSIS:\n`;
        categories.forEach((category) => {
          const budgetAmount = category.budget_amount || 0;
          const actualExpenses =
            category.expenses
              ?.filter((e) => e.status === "approved" || e.status === "paid")
              ?.reduce((sum, e) => sum + (e.amount || 0), 0) || 0;

          const variance = budgetAmount - actualExpenses;
          const variancePercent =
            budgetAmount > 0
              ? ((variance / budgetAmount) * 100).toFixed(1)
              : "0";

          totalBudget += budgetAmount;
          totalActual += actualExpenses;

          content += `- ${category.name}:\n`;
          content += `  Budget: FRw ${budgetAmount.toLocaleString()}\n`;
          content += `  Actual: FRw ${actualExpenses.toLocaleString()}\n`;
          content += `  Variance: FRw ${variance.toLocaleString()} (${variancePercent}%)\n`;
          content += `  Status: ${variance >= 0 ? "Under Budget" : "Over Budget"}\n\n`;
        });

        const totalVariance = totalBudget - totalActual;
        const totalVariancePercent =
          totalBudget > 0
            ? ((totalVariance / totalBudget) * 100).toFixed(1)
            : "0";

        content += `OVERALL SUMMARY:\n`;
        content += `Total Budget: FRw ${totalBudget.toLocaleString()}\n`;
        content += `Total Actual: FRw ${totalActual.toLocaleString()}\n`;
        content += `Total Variance: FRw ${totalVariance.toLocaleString()} (${totalVariancePercent}%)\n`;
        content += `Budget Utilization: ${totalBudget > 0 ? ((totalActual / totalBudget) * 100).toFixed(1) : "0"}%\n\n`;
      }
    } else if (report.type === "donor_report") {
      const { data: fundSources } = await supabase
        .from("fund_sources")
        .select("*, donors(name, type)");

      const totalDonations =
        fundSources?.reduce((sum, f) => sum + (f.amount || 0), 0) || 0;
      const avgDonation = fundSources?.length
        ? totalDonations / fundSources.length
        : 0;

      content += `DONOR IMPACT REPORT\n===================\n\n`;
      content += `Total Donations: FRw ${totalDonations.toLocaleString()}\n`;
      content += `Number of Donors: ${fundSources?.length || 0}\n`;
      content += `Average Donation: FRw ${Math.round(avgDonation).toLocaleString()}\n\n`;

      if (fundSources?.length) {
        content += `DONOR CONTRIBUTIONS:\n`;
        fundSources.forEach((fund, i) => {
          const donorName = fund.donors?.name || "Anonymous";
          content += `${i + 1}. ${donorName} - FRw ${(fund.amount || 0).toLocaleString()} (${fund.name}) - ${fund.received_date}\n`;
        });
        content += `\n`;
      }
    }
  } catch (error) {
    content += `ERROR: Unable to fetch real data - ${error}\n\n`;
  }

  content += `REPORT METADATA\n===============\n`;
  content += `System: Pryro for NGO Financial Management\n`;
  content += `Export Time: ${new Date().toLocaleString()}\n`;
  content += `Data Source: Live Database\n\n`;

  return content;
};

// Calculate actual file size
const calculateFileSize = (content: string): string => {
  const bytes = new Blob([content]).size;
  if (bytes < 1024) return `${bytes} B`;
  if (bytes < 1024 * 1024) return `${(bytes / 1024).toFixed(1)} KB`;
  return `${(bytes / (1024 * 1024)).toFixed(1)} MB`;
};

